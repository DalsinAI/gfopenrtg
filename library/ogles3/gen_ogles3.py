"""ogles3.library's generated parts, from ogles3_api.txt.

  gen_ogles3.py OUT_DIR [API_FILE]

Writes into OUT_DIR:
  ogles3_table.c   the dispatch table programs fetch at -30: the six agl
                   calls (ogles3_lib.c) and one entry per GL call, and the
                   name of the GL.module export each GL slot forwards to.
  ogles3_slots.h   each entry's slot, for OGLES3Check.
  ogles3_thunks.s  the GL entries: each puts its slot (x4) in D0 and its
                   arguments' size in longs (the context left out) in D1,
                   and goes to ogl3_call (ogles3_call.s).

A GL entry's arguments are counted in longs: a GLint64 or GLuint64 taken by
value is two, anything else one (the 68k's C ABI passes chars and shorts in
a long of their own).
"""
import os
import sys

TWO_LONGS = {"GLint64", "GLuint64"}


def longs(params):
    if params.strip() == "void":
        return 0
    n = 0
    for p in params.split(","):
        p = p.strip()
        if "*" in p:
            n += 1
            continue
        t = " ".join(p.replace("const", "").split()[:-1])
        n += 2 if t in TWO_LONGS else 1
    return n


def load(path):
    rows = []
    for line in open(path, encoding="ascii"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        kind, ret, name, params = line.split("|")
        rows.append((kind, ret, name, params))
    return rows


def main():
    out = sys.argv[1]
    api = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "ogles3_api.txt")
    rows = load(api)
    if len(rows) != 380:
        sys.exit("gen_ogles3: %d entries, the ABI has 380" % len(rows))
    agl = ["aglCreateContext2", "aglDestroyContext", "aglMakeCurrent", "aglSwapBuffers", "aglSetParams2", "aglSetBitmap"]
    if [r[2] for r in rows[:6]] != agl or any(r[0] != "gl" for r in rows[6:]):
        sys.exit("gen_ogles3: the agl calls must be the first six entries, the GL calls the rest")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "ogles3_thunks.s"), "w") as s:
        s.write("| Generated by library/ogles3/gen_ogles3.py: do not edit.\n")
        s.write("| One entry per GL call of the dispatch table: D0 its slot x 4, D1 its arguments in longs.\n\n\t.text\n")
        for i, (kind, ret, name, params) in enumerate(rows):
            if kind != "gl":
                continue
            s.write("\t.globl\t_ogl3_e%d\n_ogl3_e%d:\t| %s\n\tmove.l\t#%d,%%d0\n\tmoveq\t#%d,%%d1\n\tjmp\t_ogl3_call\n"
                    % (i, i, name, 4 * i, longs(params)))
    with open(os.path.join(out, "ogles3_slots.h"), "w") as h:
        h.write("/* Generated by library/ogles3/gen_ogles3.py: do not edit. Each entry's slot. */\n")
        for i, (kind, ret, name, params) in enumerate(rows):
            h.write("#define OGL3_SLOT_%s %d\n" % (name, i))
    with open(os.path.join(out, "ogles3_table.c"), "w") as c:
        c.write("/* Generated by library/ogles3/gen_ogles3.py: do not edit. */\n")
        c.write('#include "ogles3_face.h"\n\n')
        for i, (kind, ret, name, params) in enumerate(rows):
            if kind == "gl":
                c.write("extern void ogl3_e%d(void);\n" % i)
        c.write("\nconst struct ogl3_dispatch ogl3_dispatch = {\n")
        c.write("    OGL3_DISPATCH_ABI_VERSION, sizeof(struct ogl3_dispatch), OGL3_BACKEND_GFOPENGPU, 0,\n    {\n")
        for i, (kind, ret, name, params) in enumerate(rows):
            fn = ("ogl3_" + name) if kind == "agl" else ("ogl3_e%d" % i)
            c.write("        (APTR)%s,%s/* %d %s */\n" % (fn, " " * max(1, 18 - len(fn)), i, name))
        c.write("    }\n};\n\n")
        c.write("/* The GL.module export each slot forwards to (NULL: an agl call). */\n")
        c.write("const char *const ogl3_gl_names[OGL3_SLOTS] = {\n")
        for kind, ret, name, params in rows:
            c.write("    %s,\n" % ('"gl%s"' % name[2:] if kind == "gl" else "NULL"))
        c.write("};\n")


if __name__ == "__main__":
    main()
