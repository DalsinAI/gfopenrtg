# Compiles the shaders into C arrays of SPIR-V, which are kept in the
# repository so building the back end needs no shader compiler:
#   ogpu.comp    -> ogpu_vk_spv.h   (ogpu_comp_spv: the 2D commands)
#   ogpu3d.comp  -> ogpu3d_spv.h    (ogpu3d_comp_spv: the 3D range's pixels; includes ogpu3d_px.h)
#   ogpu3d_gfx.vert, ogpu3d_gfx.frag -> ogpu3d_gfx_spv.h (ogpu3d_gfx_vert_spv, ogpu3d_gfx_frag_spv:
#                   TRIANGLES on the graphics pipeline, ogpu3d_gfx.c)
#   host/vulkan/build_spv.sh [ogpu.comp | ogpu3d.comp | gfx]   (all without an argument)
# Needs glslangValidator (glslang-tools), or GLSLANG naming one: Khronos's
# glslang, from its own sources.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
GLSLANG=${GLSLANG:-glslangValidator}
one() {     # shader, header, array
    "$GLSLANG" -V --target-env vulkan1.1 --vn "$3" -o "$HERE/$2.tmp" "$HERE/$1" >/dev/null
    {
        echo "/* Generated by host/vulkan/build_spv.sh from $1: do not edit. */"
        cat "$HERE/$2.tmp"
    } > "$HERE/$2"
    rm -f "$HERE/$2.tmp"
}
gfx() {
    "$GLSLANG" -V --target-env vulkan1.1 --vn ogpu3d_gfx_vert_spv -o "$HERE/gv.tmp" "$HERE/ogpu3d_gfx.vert" >/dev/null
    "$GLSLANG" -V --target-env vulkan1.1 --vn ogpu3d_gfx_frag_spv -o "$HERE/gf.tmp" "$HERE/ogpu3d_gfx.frag" >/dev/null
    {
        echo "/* Generated by host/vulkan/build_spv.sh from ogpu3d_gfx.vert and ogpu3d_gfx.frag: do not edit. */"
        cat "$HERE/gv.tmp" "$HERE/gf.tmp"
    } > "$HERE/ogpu3d_gfx_spv.h"
    rm -f "$HERE/gv.tmp" "$HERE/gf.tmp"
}
case ${1:-all} in
ogpu.comp) one ogpu.comp ogpu_vk_spv.h ogpu_comp_spv ;;
ogpu3d.comp) one ogpu3d.comp ogpu3d_spv.h ogpu3d_comp_spv ;;
gfx) gfx ;;
all) one ogpu.comp ogpu_vk_spv.h ogpu_comp_spv; one ogpu3d.comp ogpu3d_spv.h ogpu3d_comp_spv; gfx ;;
*) echo "usage: $0 [ogpu.comp | ogpu3d.comp | gfx]" >&2; exit 2 ;;
esac
